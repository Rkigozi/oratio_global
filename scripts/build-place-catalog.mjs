import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { unzipSync, strFromU8 } from 'fflate';

// Offline generation only: no network, database credentials or live writes.
const { values } = parseArgs({ options: { source: { type: 'string' }, date: { type: 'string' } } });
if (!values.source || !/^\d{4}-\d{2}-\d{2}$/.test(values.date ?? '')) {
  throw new Error(
    'Usage: node scripts/build-place-catalog.mjs --source <directory> --date YYYY-MM-DD'
  );
}
const files = ['cities15000.zip', 'countryInfo.txt', 'admin1CodesASCII.txt'];
const buffers = Object.fromEntries(
  files.map((name) => [name, readFileSync(resolve(values.source, name))])
);
const rows = (text) =>
  text
    .split(/\r?\n/)
    .filter((line) => line && !line.startsWith('#'))
    .map((line) => line.split('\t'));
const countries = new Map(
  rows(buffers['countryInfo.txt'].toString('utf8')).map((row) => [row[0], row[4]])
);
const regions = new Map(
  rows(buffers['admin1CodesASCII.txt'].toString('utf8')).map((row) => [row[0], row[1]])
);
const key = (value) =>
  value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/’/g, '')
    .replace(/[.',-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
const londonAreas = [
  'Greater London',
  'City of London',
  'Barking and Dagenham',
  'Barnet',
  'Bexley',
  'Brent',
  'Bromley',
  'Camden',
  'Croydon',
  'Ealing',
  'Enfield',
  'Greenwich',
  'Hackney',
  'Hammersmith and Fulham',
  'Haringey',
  'Harrow',
  'Havering',
  'Hillingdon',
  'Hounslow',
  'Islington',
  'Kensington and Chelsea',
  'Kingston upon Thames',
  'Lambeth',
  'Lewisham',
  'Merton',
  'Newham',
  'Redbridge',
  'Richmond upon Thames',
  'Southwark',
  'Sutton',
  'Tower Hamlets',
  'Waltham Forest',
  'Wandsworth',
  'Westminster',
];
const londonKeys = new Set(londonAreas.map(key));
const codes = new Set(['PPL', 'PPLA', 'PPLA2', 'PPLA3', 'PPLA4', 'PPLA5', 'PPLC', 'PPLG']);
const archive = unzipSync(buffers['cities15000.zip']);
if (!archive['cities15000.txt']) throw new Error('Missing cities15000.txt in archive');
const cities = [];
const ids = new Set();
for (const row of rows(strFromU8(archive['cities15000.txt']))) {
  if (row.length !== 19) throw new Error('Unexpected GeoNames column count');
  const [
    sourceId,
    sourceName,
    asciiName,
    alternateNames,
    rawLat,
    rawLng,
    featureClass,
    code,
    countryCode,
  ] = row;
  if (featureClass !== 'P' || !codes.has(code) || !countries.has(countryCode)) continue;
  if (countryCode === 'GB' && londonKeys.has(key(sourceName))) continue;
  const id = `geonames:${sourceId}`;
  const latitude = Math.round(Number(rawLat) * 100) / 100;
  const longitude = Math.round(Number(rawLng) * 100) / 100;
  const population = Number(row[14]);
  if (
    !/^\d+$/.test(sourceId) ||
    ids.has(id) ||
    !Number.isFinite(latitude) ||
    !Number.isFinite(longitude) ||
    Math.abs(latitude) > 90 ||
    Math.abs(longitude) > 180 ||
    !Number.isSafeInteger(population) ||
    population < 0
  ) {
    throw new Error(`Invalid catalog record: ${id}`);
  }
  ids.add(id);
  const city = sourceId === '5128581' ? 'New York' : sourceName;
  const region = regions.get(`${countryCode}.${row[10]}`) ?? '';
  const country = countries.get(countryCode);
  const names = [city, sourceName, asciiName, ...alternateNames.split(',')];
  if (sourceId === '2643743')
    names.push(...londonAreas, ...londonAreas.map((area) => `London Borough of ${area}`));
  const aliases = [
    ...new Set(names.map(key).filter((value) => value.length > 0 && value.length <= 200)),
  ].sort();
  const countryAliases =
    countryCode === 'GB'
      ? 'UK Britain Great Britain England Scotland Wales Northern Ireland'
      : countryCode === 'US'
        ? 'USA United States of America'
        : countryCode === 'AE'
          ? 'UAE'
          : '';
  const search = key([city, region, countryCode, country, countryAliases, ...names].join(' '));
  cities.push({
    id,
    city,
    region,
    countryCode,
    country,
    latitude,
    longitude,
    population,
    aliases,
    search,
  });
}
if (cities.length < 20000 || !ids.has('geonames:2643743') || !ids.has('geonames:232422')) {
  throw new Error('Catalog unexpectedly incomplete');
}
cities.sort((a, b) => a.id.localeCompare(b.id, 'en'));
const quote = (value) => `'${String(value).replaceAll("'", "''")}'`;
const seed = cities.map(({ search: _search, ...place }) => place);
const hashes = files
  .map((name) => `-- ${name} SHA-256 ${createHash('sha256').update(buffers[name]).digest('hex')}`)
  .join('\n');
const sql = `-- Generated by scripts/build-place-catalog.mjs; do not hand-edit or regenerate after rollout.
-- GeoNames cities15000, countryInfo and admin1CodesASCII; retrieved ${values.date}.
-- Sources: https://download.geonames.org/export/dump/ ; https://www.geonames.org/export/
-- CC BY 4.0: https://creativecommons.org/licenses/by/4.0/ ; attribution: GeoNames.
-- Excludes neighbourhood/historical features and coalesces legacy London borough aliases.
-- Fixed catalog centroids rounded to two decimal places, never device coordinates.
${hashes}
create temporary table oratio_place_seed as select * from jsonb_to_recordset(${quote(JSON.stringify(seed))}::jsonb)
  as p(id text, city text, region text, "countryCode" text, country text,
    latitude double precision, longitude double precision, population bigint, aliases jsonb);
insert into public.prayer_places(id, city, region, country_code, country, latitude, longitude, population, search_text)
select id, city, region, "countryCode", country, latitude, longitude, population,
  public.prayer_location_key(concat_ws(' ', city, region, "countryCode", country,
    case "countryCode" when 'GB' then 'UK Britain Great Britain England Scotland Wales Northern Ireland'
      when 'US' then 'USA United States of America' when 'AE' then 'UAE' else '' end,
    (select string_agg(value, ' ') from jsonb_array_elements_text(aliases))))
from oratio_place_seed;
insert into public.prayer_place_aliases(place_id, country_code, alias_key)
select p.id, p."countryCode", a.value from oratio_place_seed p
cross join lateral jsonb_array_elements_text(p.aliases) a;
drop table oratio_place_seed;
-- Reconcile old names without deleting prayers, changing IDs, audiences or expiry.
-- The trigger strips unverified coordinates and location from private prayers.
update public.prayer_requests set location_place_id = null;
notify pgrst, 'reload schema';
`;
writeFileSync(
  new URL('../supabase/migrations/045_prayer_place_catalog_data.sql', import.meta.url),
  sql
);
console.log(
  JSON.stringify({
    places: cities.length,
    countries: new Set(cities.map((p) => p.countryCode)).size,
    bytes: Buffer.byteLength(sql),
    sha256: createHash('sha256').update(sql).digest('hex'),
  })
);
